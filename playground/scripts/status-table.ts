import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { isTreatment } from "../types.ts";
import type { Treatment } from "../types.ts";
import { listSnapshotRecords } from "./lib/review.ts";
import { reviewSnapshotDirectory } from "./lib/review-snapshot.ts";
import { environmentMatrix, PLAYGROUND_DIRECTORY } from "./lib/run-metadata.ts";

const STATUS_HEADER = "<!-- generated by playground:status, do not edit -->";
const STATUS_FILE = "status.md";
const DEFAULT_INVENTORY = join(PLAYGROUND_DIRECTORY, "scenarios", "capability-inventory.json");

export interface StatusRow {
  capability: string;
  scenario: string;
  verdict: string;
  mechanicalFailures: number;
  recordLink: string;
}

export interface StatusTarget {
  treatment: Treatment;
  environment: string;
  root?: string;
  inventoryFile?: string;
  /** Resolve a scenario's own `capability` field; the registry supplies this in the CLI. */
  resolveCapability?: (scenarioId: string) => string | undefined;
}

interface Inventory {
  capabilities?: Array<{ id?: unknown; probes?: unknown }>;
}

/** Map every probe id in the capability inventory back to its capability id. */
function inventoryCapabilities(file: string): Map<string, string> {
  const map = new Map<string, string>();
  if (!existsSync(file)) return map;
  const parsed = JSON.parse(readFileSync(file, "utf8")) as Inventory;
  for (const capability of Array.isArray(parsed.capabilities) ? parsed.capabilities : []) {
    if (typeof capability.id !== "string") continue;
    const probes = capability.probes;
    if (probes === null || typeof probes !== "object") continue;
    for (const probe of Object.values(probes as Record<string, unknown>)) {
      if (typeof probe === "string") map.set(probe, capability.id);
    }
  }
  return map;
}

export function statusRows(target: StatusTarget): StatusRow[] {
  const records = listSnapshotRecords(target.treatment, target.environment, target.root);
  const inventory = inventoryCapabilities(target.inventoryFile ?? DEFAULT_INVENTORY);
  return records.map(({ scenarioId, record }) => ({
    capability:
      target.resolveCapability?.(scenarioId) ?? inventory.get(scenarioId) ?? scenarioId,
    scenario: scenarioId,
    verdict: record.verdict.status,
    mechanicalFailures: (record.mechanicalFailures ?? []).length,
    recordLink: `scenarios/${scenarioId}/${target.treatment}-${target.environment}/record.json`,
  }));
}

export function statusTableContent(target: StatusTarget): string {
  const rows = statusRows(target);
  const lines = [
    "| capability | scenario | verdict | mechanical failures | record |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map(
      (row) =>
        `| ${row.capability} | ${row.scenario} | ${row.verdict} | ${row.mechanicalFailures} | [record.json](${row.recordLink}) |`,
    ),
  ];
  return `${STATUS_HEADER}\n\n${lines.join("\n")}\n`;
}

export function statusFilePath(target: StatusTarget): string {
  return join(reviewSnapshotDirectory(target.treatment, target.environment, target.root), STATUS_FILE);
}

export function writeStatusTable(target: StatusTarget): { file: string; content: string } {
  const content = statusTableContent(target);
  const file = statusFilePath(target);
  writeFileSync(file, content);
  return { file, content };
}

export function checkStatusTable(target: StatusTarget): { ok: boolean; file: string } {
  const file = statusFilePath(target);
  const ok = existsSync(file) && readFileSync(file, "utf8") === statusTableContent(target);
  return { ok, file };
}

async function registryCapabilityResolver(): Promise<
  ((scenarioId: string) => string | undefined) | undefined
> {
  try {
    const { loadScenario } = await import("./lib/scenarios.ts");
    return (scenarioId: string) => {
      try {
        return loadScenario(scenarioId).capability;
      } catch {
        return undefined;
      }
    };
  } catch {
    return undefined;
  }
}

function argValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

async function main(): Promise<void> {
  const treatment = argValue("--treatment") as Treatment | undefined;
  const environment = argValue("--environment");
  if (!isTreatment(treatment) || environment === undefined) {
    throw new Error(
      "usage: status-table.ts --treatment native|adapted --environment ID [--write | --check]",
    );
  }
  environmentMatrix(environment);
  const write = process.argv.includes("--write");
  const check = process.argv.includes("--check");
  if (write && check) throw new Error("pass at most one of --write or --check");
  const target: StatusTarget = {
    treatment,
    environment,
    resolveCapability: await registryCapabilityResolver(),
  };
  if (check) {
    const { ok, file } = checkStatusTable(target);
    if (!ok) {
      console.error(`[status] ${file} is stale; run playground:status-table --write`);
      process.exitCode = 1;
      return;
    }
    console.log(`[status] ${file} is current`);
    return;
  }
  if (write) {
    const { file } = writeStatusTable(target);
    console.log(`[status] wrote ${file}`);
    return;
  }
  process.stdout.write(statusTableContent(target));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error: unknown) => {
    console.error(`[status] ERROR: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  });
}
