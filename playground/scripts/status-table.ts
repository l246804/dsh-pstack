import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import type { Treatment } from "../types.ts";
import { listSnapshotRecords } from "./lib/review.ts";
import { PLAYGROUND_DIRECTORY } from "./lib/run-metadata.ts";
import { REVIEWS_DIRECTORY } from "./lib/review-snapshot.ts";

const STATUS_HEADER = "<!-- generated by playground:status-table, do not edit -->";
const STATUS_FILE = "status.md";
const DEFAULT_INVENTORY = join(PLAYGROUND_DIRECTORY, "scenarios", "capability-inventory.json");
const SNAPSHOT_DIRECTORY = /^(native|adapted)-(.+)$/;

export interface StatusPivotTarget {
  root?: string;
  inventoryFile?: string;
  /** Resolve a scenario's own `capability` field; the registry supplies this in the CLI. */
  resolveCapability?: (scenarioId: string) => string | undefined;
}

export interface StatusPivotColumn {
  treatment: Treatment;
  environment: string;
  /** Column heading and cell key: `${treatment}/${environment}`. */
  key: string;
}

export interface StatusPivotRow {
  capability: string;
  scenario: string;
  /** Status per column key; a missing cell means the record does not exist. */
  cells: Record<string, string | undefined>;
  /** Record link per column key, relative to the pivot file. */
  links: Record<string, string | undefined>;
}

export interface StatusPivot {
  columns: StatusPivotColumn[];
  rows: StatusPivotRow[];
}

interface Inventory {
  capabilities?: Array<{ id?: unknown; probes?: unknown }>;
}

/** Map every probe id in the capability inventory back to its capability id. */
function inventoryCapabilities(file: string): Map<string, string> {
  const map = new Map<string, string>();
  if (!existsSync(file)) return map;
  const parsed = JSON.parse(readFileSync(file, "utf8")) as Inventory;
  for (const capability of Array.isArray(parsed.capabilities) ? parsed.capabilities : []) {
    if (typeof capability.id !== "string") continue;
    const probes = capability.probes;
    if (probes === null || typeof probes !== "object") continue;
    for (const probe of Object.values(probes as Record<string, unknown>)) {
      if (typeof probe === "string") map.set(probe, capability.id);
    }
  }
  return map;
}

function cellKey(treatment: Treatment, environment: string): string {
  return `${treatment}/${environment}`;
}

/**
 * Read every committed `<treatment>-<environment>` snapshot under `root` and pivot the
 * records: one row per scenario, one column per treatment x environment cell. Generated
 * from records only, so `--check` can prove the committed pivot does not drift.
 */
export function statusPivot(target: StatusPivotTarget = {}): StatusPivot {
  const root = target.root ?? REVIEWS_DIRECTORY;
  const inventory = inventoryCapabilities(target.inventoryFile ?? DEFAULT_INVENTORY);
  const columns = new Map<string, StatusPivotColumn>();
  const rowsByScenario = new Map<string, StatusPivotRow>();

  const directories = existsSync(root)
    ? readdirSync(root, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
        .map((entry) => entry.name)
    : [];

  for (const name of directories) {
    const match = SNAPSHOT_DIRECTORY.exec(name);
    if (!match) continue;
    const treatment = match[1] as Treatment;
    const environment = match[2] as string;
    const key = cellKey(treatment, environment);
    columns.set(key, { treatment, environment, key });
    for (const { scenarioId, record } of listSnapshotRecords(treatment, environment, root)) {
      const row = rowsByScenario.get(scenarioId) ?? {
        capability:
          target.resolveCapability?.(scenarioId) ?? inventory.get(scenarioId) ?? scenarioId,
        scenario: scenarioId,
        cells: {},
        links: {},
      };
      row.cells[key] = record.verdict.status;
      row.links[key] = `${name}/scenarios/${scenarioId}/${name}/record.json`;
      rowsByScenario.set(scenarioId, row);
    }
  }

  const sortedColumns = [...columns.values()].sort(
    (left, right) =>
      left.environment.localeCompare(right.environment) ||
      (left.treatment === right.treatment ? 0 : left.treatment === "native" ? -1 : 1),
  );
  const rows = [...rowsByScenario.values()].sort(
    (left, right) =>
      left.capability.localeCompare(right.capability) ||
      left.scenario.localeCompare(right.scenario),
  );
  return { columns: sortedColumns, rows };
}

export function statusTableContent(target: StatusPivotTarget = {}): string {
  const pivot = statusPivot(target);
  const header = ["capability", "scenario", ...pivot.columns.map((column) => column.key)];
  const separator = header.map(() => "---");
  const body = pivot.rows.map((row) => {
    const cells = pivot.columns.map((column) => {
      const status = row.cells[column.key];
      if (status === undefined) return "-";
      const link = row.links[column.key];
      return link === undefined ? status : `[${status}](${link})`;
    });
    return [row.capability, row.scenario, ...cells];
  });
  const lines = [header, separator, ...body].map((cells) => `| ${cells.join(" | ")} |`);
  return `${STATUS_HEADER}\n\n${lines.join("\n")}\n`;
}

export function statusFilePath(target: StatusPivotTarget = {}): string {
  return join(target.root ?? REVIEWS_DIRECTORY, STATUS_FILE);
}

export function writeStatusTable(target: StatusPivotTarget = {}): {
  file: string;
  content: string;
} {
  const content = statusTableContent(target);
  const file = statusFilePath(target);
  writeFileSync(file, content);
  return { file, content };
}

export function checkStatusTable(target: StatusPivotTarget = {}): { ok: boolean; file: string } {
  const file = statusFilePath(target);
  const ok = existsSync(file) && readFileSync(file, "utf8") === statusTableContent(target);
  return { ok, file };
}

async function registryCapabilityResolver(): Promise<
  ((scenarioId: string) => string | undefined) | undefined
> {
  try {
    const { loadScenario } = await import("./lib/scenarios.ts");
    return (scenarioId: string) => {
      try {
        return loadScenario(scenarioId).capability;
      } catch {
        return undefined;
      }
    };
  } catch {
    return undefined;
  }
}

function argValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

async function main(): Promise<void> {
  const write = process.argv.includes("--write");
  const check = process.argv.includes("--check");
  if (write && check) throw new Error("pass at most one of --write or --check");
  const root = argValue("--root");
  const target: StatusPivotTarget = {
    ...(root === undefined ? {} : { root }),
    resolveCapability: await registryCapabilityResolver(),
  };
  if (check) {
    const { ok, file } = checkStatusTable(target);
    if (!ok) {
      console.error(`[status] ${file} is stale; run playground:status-table --write`);
      process.exitCode = 1;
      return;
    }
    console.log(`[status] ${file} is current`);
    return;
  }
  if (write) {
    const { file } = writeStatusTable(target);
    console.log(`[status] wrote ${file}`);
    return;
  }
  process.stdout.write(statusTableContent(target));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error: unknown) => {
    console.error(`[status] ERROR: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  });
}
